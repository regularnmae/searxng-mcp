"""Resolve the runtime dependency closure on the image's Python.

Run this to regenerate requirements.lock:

    podman run --rm -v "$PWD:/app:z" -w /app docker.io/library/python:3.14-alpine \
        .venv/bin/python scripts/lock.py     # on the host:
    podman run --rm -v "$PWD:/app:z" -w /app docker.io/library/python:3.14-alpine \
        python scripts/lock.py

It installs requirements.txt into a throwaway prefix, freezes the
result, and writes it back with the direct requirements first so the
lock stays readable.
"""

from __future__ import annotations

import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent / "requirements.txt"
LOCK = Path(__file__).resolve().parent.parent / "requirements.lock"


def main() -> int:
    direct = [line.strip() for line in HERE.read_text().splitlines() if line.strip()]

    with tempfile.TemporaryDirectory() as tmp:
        target = f"--target={tmp}"
        subprocess.run(
            [sys.executable, "-m", "pip", "install", "--quiet", "--no-cache-dir",
             "--disable-pip-version-check", target, *direct],
            check=True,
        )
        frozen = subprocess.run(
            [sys.executable, "-m", "pip", "freeze", "--path", tmp],
            check=True, capture_output=True, text=True,
        ).stdout.splitlines()

    # Keep the direct pins at the top, everything below sorted, so a
    # diff of this file reads like a change of intent rather than a
    # reshuffle of the closure.
    direct_names = {d.split(">=")[0].split("==")[0].lower() for d in direct}
    head = sorted(
        line for line in frozen if line.split("==")[0].lower() in direct_names
    )
    rest = sorted(
        line for line in frozen if line.split("==")[0].lower() not in direct_names
    )
    LOCK.write_text(
        "# Generated by scripts/lock.py from requirements.txt; do not edit.\n"
        "# Install with: pip install -r requirements.lock\n"
        + "\n".join(head + rest) + "\n"
    )
    print(f"wrote {LOCK.name}: {len(head)} direct, {len(rest)} transitive")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
